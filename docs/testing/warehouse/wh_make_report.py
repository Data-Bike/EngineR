def ops_brief(step):
    """Compact 'что сделано' from a step's ops."""
    created, rels, upds, reads = [], [], [], 0
    fails = []
    for op in step["ops"]:
        t, r = op["tool"], op["result"]
        if not op["ok"]:
            fails.append(t)
        if t == "entities.create" and isinstance(r, dict):
            pid = r.get("public_id")
            code = PID2CODE.get(pid, pid)
            oc = r.get("outcome", "")
            if code:
                created.append(f"{code} ({oc})" if oc else code)
        elif t == "relations.create" and op["ok"]:
            rels.append((r or {}).get("predicate", "?"))
        elif t == "entities.update":
            upds.append(op["args"]["id"])
        elif t in ("entities.list", "entities.get", "relations.list",
                   "entities.query", "entities.history", "audit.query",
                   "dashboard.stats"):
            reads += 1
    parts = []
    if created:
        parts.append("создано: " + ", ".join(created))
    if rels:
        parts.append(f"рёбер: {len(rels)}")
    if upds:
        parts.append(f"обновлено: {len(upds)}")
    if reads:
        parts.append(f"чтений: {reads}")
    if fails:
        parts.append(f"ОШИБКИ: {fails}")
    return "; ".join(parts) or "—"


def ids_of(step):
    out = []
    for op in step["ops"]:
        if op["tool"] == "entities.create" and op["ok"]:
            pid = (op["result"] or {}).get("public_id")
            code = PID2CODE.get(pid)
            if code:
                out.append(f"{code}={pid}")
    return "; ".join(out)


