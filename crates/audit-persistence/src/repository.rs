//! Audit repository: trait + PostgreSQL implementation (docs/08 §11).
//!
//! The repository handles:
//! - Inserting audit entries with tamper-evident chain hashing
//! - Querying audit entries with filters + cursor pagination
//! - Creating and retrieving chain checkpoints
//! - Managing retention policies
//!
//! Audit rows are insert-only from the application role; no UPDATE/DELETE
//! is granted to enginer_app (docs/08 §11).

use crate::chain::{ChainHasher, ChainState};
use crate::error::{AuditPersistenceError, AuditPersistenceResult};
use enginer_security::{AuditEntry, AuditKind};
use std::sync::Arc;

/// Audit record (stored in the database).
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct AuditRecord {
    /// Database audit_id (auto-generated).
    pub audit_id: i64,
    /// Chain sequence number.
    pub sequence: i64,
    /// Previous entry hash (chain link).
    pub previous_hash: String,
    /// This entry's hash.
    pub entry_hash: String,
    /// Tenant ID.
    pub tenant_id: String,
    /// Timestamp.
    pub occurred_at: chrono::DateTime<chrono::Utc>,
    /// Actor (user/service who performed the action).
    pub actor: String,
    /// Effective actor (if impersonating, docs/08 §12).
    pub effective_actor: Option<String>,
    /// Audit kind.
    pub kind: String,
    /// Action performed.
    pub action: String,
    /// Resource kind.
    pub resource_kind: String,
    /// Resource ID.
    pub resource_id: Option<String>,
    /// Decision/effect (allow/deny).
    pub effect: Option<String>,
    /// Reason IDs (policy rule IDs).
    pub reason_ids: Vec<String>,
    /// Policy revision ID.
    pub policy_revision: Option<i64>,
    /// Request ID.
    pub request_id: Option<String>,
    /// Correlation ID.
    pub correlation_id: Option<String>,
    /// Query fingerprint.
    pub query_fingerprint: Option<String>,
    /// Row count affected.
    pub row_count: Option<i64>,
    /// Bytes transferred.
    pub bytes: Option<i64>,
    /// Client.
    pub client: Option<String>,
    /// Service.
    pub service: Option<String>,
    /// Additional metadata.
    pub metadata: serde_json::Value,
}

impl AuditRecord {
    /// Convert from an `AuditEntry` (from the security crate) to an
    /// `AuditRecord` (for persistence), computing the chain hash.
    pub fn from_entry(
        entry: &AuditEntry,
        chain_state: &ChainState,
    ) -> AuditPersistenceResult<Self> {
        let sequence = chain_state.last_sequence;
        let entry_hash = ChainHasher::compute_hash(
            sequence,
            &chain_state.last_hash,
            entry.timestamp,
            &entry.tenant_id,
            &entry.actor,
            &entry.action,
            audit_kind_str(entry.kind),
            "entity", // default resource_kind
            entry.resource_id.as_deref(),
            entry.decision.as_deref(),
        )?;

        Ok(Self {
            audit_id: 0, // auto-generated by DB
            sequence,
            previous_hash: chain_state.last_hash.clone(),
            entry_hash,
            tenant_id: entry.tenant_id.clone(),
            occurred_at: entry.timestamp,
            actor: entry.actor.clone(),
            effective_actor: entry.effective_actor.clone(),
            kind: audit_kind_str(entry.kind).to_string(),
            action: entry.action.clone(),
            resource_kind: entry
                .resource_type
                .clone()
                .unwrap_or_else(|| "entity".to_string()),
            resource_id: entry.resource_id.clone(),
            effect: entry.decision.clone(),
            reason_ids: entry.reason_ids.clone(),
            policy_revision: None, // extracted from entry if available
            request_id: entry.request_id.clone(),
            correlation_id: entry.correlation_id.clone(),
            query_fingerprint: entry.query_fingerprint.clone(),
            row_count: entry.row_count.map(|n| n as i64),
            bytes: entry.bytes.map(|n| n as i64),
            client: entry.client.clone(),
            service: entry.service.clone(),
            metadata: serde_json::to_value(&entry.metadata).unwrap_or(serde_json::Value::Null),
        })
    }
}

/// Convert `AuditKind` to its string representation.
fn audit_kind_str(kind: AuditKind) -> &'static str {
    match kind {
        AuditKind::Authentication => "authentication",
        AuditKind::Decision => "decision",
        AuditKind::DeniedRequest => "denied_request",
        AuditKind::PolicyChange => "policy_change",
        AuditKind::Export => "export",
        AuditKind::BlobRead => "blob_read",
        AuditKind::BulkAction => "bulk_action",
        AuditKind::BreakGlass => "break_glass",
        AuditKind::Impersonation => "impersonation",
    }
}

/// Audit query (docs/08 §11).
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct AuditQuery {
    /// Tenant ID (required for isolation).
    pub tenant_id: String,
    /// Filter by kind (optional).
    pub kind: Option<String>,
    /// Filter by actor (optional).
    pub actor: Option<String>,
    /// Filter by action (optional).
    pub action: Option<String>,
    /// Filter by resource kind (optional).
    pub resource_kind: Option<String>,
    /// Filter by resource ID (optional).
    pub resource_id: Option<String>,
    /// Filter by effect/decision (optional).
    pub effect: Option<String>,
    /// Filter from timestamp.
    pub from: Option<chrono::DateTime<chrono::Utc>>,
    /// Filter to timestamp.
    pub to: Option<chrono::DateTime<chrono::Utc>>,
    /// Limit (max entries to return).
    pub limit: Option<u32>,
    /// Cursor for pagination (sequence number, returns entries after this).
    pub cursor: Option<i64>,
}

impl AuditQuery {
    /// Create a new query for a tenant.
    pub fn for_tenant(tenant_id: &str) -> Self {
        Self {
            tenant_id: tenant_id.to_string(),
            kind: None,
            actor: None,
            action: None,
            resource_kind: None,
            resource_id: None,
            effect: None,
            from: None,
            to: None,
            limit: Some(100),
            cursor: None,
        }
    }

    /// Filter by kind.
    pub fn with_kind(mut self, kind: &str) -> Self {
        self.kind = Some(kind.to_string());
        self
    }

    /// Filter by actor.
    pub fn with_actor(mut self, actor: &str) -> Self {
        self.actor = Some(actor.to_string());
        self
    }

    /// Filter by action.
    pub fn with_action(mut self, action: &str) -> Self {
        self.action = Some(action.to_string());
        self
    }

    /// Filter by effect.
    pub fn with_effect(mut self, effect: &str) -> Self {
        self.effect = Some(effect.to_string());
        self
    }

    /// Set limit.
    pub fn with_limit(mut self, limit: u32) -> Self {
        self.limit = Some(limit);
        self
    }

    /// Set cursor.
    pub fn with_cursor(mut self, cursor: i64) -> Self {
        self.cursor = Some(cursor);
        self
    }

    /// Set time range.
    pub fn with_time_range(
        mut self,
        from: chrono::DateTime<chrono::Utc>,
        to: chrono::DateTime<chrono::Utc>,
    ) -> Self {
        self.from = Some(from);
        self.to = Some(to);
        self
    }
}

