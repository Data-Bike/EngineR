    #[test]
    fn in_memory_tenant_isolation() {
        let repo = InMemoryAuditRepository::new();
        repo.insert(&make_entry("tenant-A", "u", "a", AuditKind::Decision))
            .unwrap();
        repo.insert(&make_entry("tenant-B", "u", "a", AuditKind::Decision))
            .unwrap();

        let results_a = repo.query(&AuditQuery::for_tenant("tenant-A")).unwrap();
        let results_b = repo.query(&AuditQuery::for_tenant("tenant-B")).unwrap();
        assert_eq!(results_a.len(), 1);
        assert_eq!(results_b.len(), 1);
        assert_eq!(results_a[0].tenant_id, "tenant-A");
        assert_eq!(results_b[0].tenant_id, "tenant-B");
    }

    #[test]
    fn audit_record_from_entry_computes_hash() {
        let entry = make_entry("t", "u", "a", AuditKind::Decision);
        let state = ChainState::new();
        let record = AuditRecord::from_entry(&entry, &state).unwrap();
        assert_eq!(record.sequence, 0); // first entry
        assert!(!record.entry_hash.is_empty());
        assert_eq!(record.previous_hash, state.last_hash);
    }

