/// Audit repository trait (docs/08 §11).
///
/// Implementations:
/// - `PgAuditRepository`: PostgreSQL with RLS
/// - Mock implementations for testing
pub trait AuditRepository: Send + Sync {
    /// Insert an audit entry (computes chain hash, updates chain state).
    fn insert(&self, entry: &AuditEntry) -> AuditPersistenceResult<AuditRecord>;

    /// Query audit entries with filters + cursor pagination.
    fn query(&self, query: &AuditQuery) -> AuditPersistenceResult<Vec<AuditRecord>>;

    /// Get the current chain state for a tenant (last sequence + hash).
    fn chain_state(&self, tenant_id: &str) -> AuditPersistenceResult<ChainState>;

    /// Create a checkpoint at the current chain state.
    fn checkpoint(&self, tenant_id: &str) -> AuditPersistenceResult<ChainCheckpoint>;

    /// Get the latest checkpoint for a tenant.
    fn latest_checkpoint(&self, tenant_id: &str) -> AuditPersistenceResult<Option<ChainCheckpoint>>;

    /// Verify the chain integrity for a tenant (returns true if valid).
    fn verify_chain(&self, tenant_id: &str) -> AuditPersistenceResult<bool>;

    /// Get the retention policy for a tenant.
    fn retention_policy(&self, tenant_id: &str) -> AuditPersistenceResult<RetentionPolicyRecord>;

    /// Set the retention policy for a tenant.
    fn set_retention_policy(
        &self,
        policy: &RetentionPolicyRecord,
    ) -> AuditPersistenceResult<()>;
}

/// In-memory audit repository (for testing).
pub struct InMemoryAuditRepository {
    records: std::sync::Mutex<Vec<AuditRecord>>,
    chain_states: std::sync::Mutex<std::collections::HashMap<String, ChainState>>,
    checkpoints: std::sync::Mutex<Vec<ChainCheckpoint>>,
    retention_policies:
        std::sync::Mutex<std::collections::HashMap<String, RetentionPolicyRecord>>,
}

impl InMemoryAuditRepository {
    /// Create a new empty in-memory repository.
    pub fn new() -> Self {
        Self {
            records: std::sync::Mutex::new(Vec::new()),
            chain_states: std::sync::Mutex::new(std::collections::HashMap::new()),
            checkpoints: std::sync::Mutex::new(Vec::new()),
            retention_policies: std::sync::Mutex::new(std::collections::HashMap::new()),
        }
    }

    /// Get the number of stored records.
    pub fn count(&self) -> usize {
        self.records.lock().unwrap().len()
    }
}

impl Default for InMemoryAuditRepository {
    fn default() -> Self {
        Self::new()
    }
}

impl AuditRepository for InMemoryAuditRepository {
    fn insert(&self, entry: &AuditEntry) -> AuditPersistenceResult<AuditRecord> {
        let mut states = self.chain_states.lock().unwrap();
        let state = states
            .entry(entry.tenant_id.clone())
            .or_insert_with(ChainState::new);
        let mut record = AuditRecord::from_entry(entry, state)?;

        // Update chain state
        state.last_sequence = record.sequence + 1;
        state.last_hash = record.entry_hash.clone();

        // Store record
        let mut records = self.records.lock().unwrap();
        record.audit_id = (records.len() + 1) as i64;
        records.push(record.clone());

        Ok(record)
    }

    fn query(&self, query: &AuditQuery) -> AuditPersistenceResult<Vec<AuditRecord>> {
        let records = self.records.lock().unwrap();
        let mut filtered: Vec<AuditRecord> = records
            .iter()
            .filter(|r| r.tenant_id == query.tenant_id)
            .filter(|r| query.kind.as_ref().map_or(true, |k| &r.kind == k))
            .filter(|r| query.actor.as_ref().map_or(true, |a| &r.actor == a))
            .filter(|r| query.action.as_ref().map_or(true, |a| &r.action == a))
            .filter(|r| {
                query
                    .resource_kind
                    .as_ref()
                    .map_or(true, |k| &r.resource_kind == k)
            })
            .filter(|r| {
                query
                    .resource_id
                    .as_ref()
                    .map_or(true, |id| r.resource_id.as_ref().is_some_and(|rid| rid == id))
            })
            .filter(|r| query.effect.as_ref().map_or(true, |e| r.effect.as_ref().is_some_and(|re| re == e)))
            .filter(|r| query.from.map_or(true, |f| r.occurred_at >= f))
            .filter(|r| query.to.map_or(true, |t| r.occurred_at <= t))
            .filter(|r| query.cursor.map_or(true, |c| r.sequence > c))
            .cloned()
            .collect();

        // Sort by sequence ascending
        filtered.sort_by_key(|r| r.sequence);

        // Apply limit
        if let Some(limit) = query.limit {
            filtered.truncate(limit as usize);
        }

        Ok(filtered)
    }

    fn chain_state(&self, tenant_id: &str) -> AuditPersistenceResult<ChainState> {
        let states = self.chain_states.lock().unwrap();
        Ok(states
            .get(tenant_id)
            .cloned()
            .unwrap_or_else(ChainState::new))
    }

    fn checkpoint(&self, tenant_id: &str) -> AuditPersistenceResult<ChainCheckpoint> {
        let state = self.chain_state(tenant_id)?;
        let checkpoint = ChainCheckpoint {
            checkpoint_id: 0, // auto-generated in PG
            tenant_id: tenant_id.to_string(),
            sequence: state.last_sequence,
            entry_hash: state.last_hash.clone(),
            created_at: chrono::Utc::now(),
        };
        self.checkpoints.lock().unwrap().push(checkpoint.clone());
        Ok(checkpoint)
    }

    fn latest_checkpoint(
        &self,
        tenant_id: &str,
    ) -> AuditPersistenceResult<Option<ChainCheckpoint>> {
        let checkpoints = self.checkpoints.lock().unwrap();
        Ok(checkpoints
            .iter()
            .filter(|c| c.tenant_id == tenant_id)
            .last()
            .cloned())
    }

    fn verify_chain(&self, tenant_id: &str) -> AuditPersistenceResult<bool> {
        let records = self.records.lock().unwrap();
        let entries: Vec<crate::chain::ChainEntry> = records
            .iter()
            .filter(|r| r.tenant_id == tenant_id)
            .map(|r| crate::chain::ChainEntry {
                sequence: r.sequence,
                previous_hash: r.previous_hash.clone(),
                entry_hash: r.entry_hash.clone(),
                timestamp: r.occurred_at,
                tenant_id: r.tenant_id.clone(),
                actor: r.actor.clone(),
                action: r.action.clone(),
                kind: r.kind.clone(),
                resource_kind: r.resource_kind.clone(),
                resource_id: r.resource_id.clone(),
                effect: r.effect.clone(),
            })
            .collect();

        ChainHasher::verify_chain(&entries)
    }

    fn retention_policy(&self, tenant_id: &str) -> AuditPersistenceResult<RetentionPolicyRecord> {
        let policies = self.retention_policies.lock().unwrap();
        Ok(policies
            .get(tenant_id)
            .cloned()
            .unwrap_or_else(|| RetentionPolicyRecord {
                tenant_id: tenant_id.to_string(),
                ..Default::default()
            }))
    }

    fn set_retention_policy(
        &self,
        policy: &RetentionPolicyRecord,
    ) -> AuditPersistenceResult<()> {
        let mut policies = self.retention_policies.lock().unwrap();
        policies.insert(policy.tenant_id.clone(), policy.clone());
        Ok(())
    }
}

