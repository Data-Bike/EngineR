//             $14, $15, $16, $17, $18, $19, $20, $21)
//   RETURNING audit_id
//
// QUERY:
//   SELECT * FROM audit.event
//   WHERE tenant_id = $1
//     AND ($2::text IS NULL OR kind = $2)
//     AND ($3::text IS NULL OR principal_id::text = $3)
//     AND ($4::text IS NULL OR action = $4)
//     AND ($5::text IS NULL OR resource_kind = $5)
//     AND ($6::uuid IS NULL OR resource_id = $6)
//     AND ($7::text IS NULL OR effect = $7)
//     AND ($8::timestamptz IS NULL OR occurred_at >= $8)
//     AND ($9::timestamptz IS NULL OR occurred_at <= $9)
//     AND ($10::bigint IS NULL OR sequence > $10)
//   ORDER BY sequence ASC
//   LIMIT $11
//
// CHAIN_STATE:
//   SELECT sequence, entry_hash FROM audit.event
//   WHERE tenant_id = $1
//   ORDER BY sequence DESC
//   LIMIT 1
//
